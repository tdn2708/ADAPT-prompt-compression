"""Token counts of the prompt levels and one example per level -> data/PROMPTS.md.

    python -m experiments.prompt_tokens [--data data]

Tokens include the chat template and the answer prefix; tokenizers of Qwen2.5 (the same for 0.5B, 1.5B and 3B) and
Phi-3-mini, loaded from the local Hugging Face cache.
"""

import argparse
import json
from pathlib import Path

import numpy as np
from transformers import AutoTokenizer

from adapt.prompts import LEVELS, Prompter, user_text

ap = argparse.ArgumentParser()
ap.add_argument('--data', default=str(Path(__file__).resolve().parent.parent / 'data'))
a = ap.parse_args()
DATA = Path(a.data)
FILES = ['test', 'unseen', 'longer_than_train']
rows = {f: [json.loads(l) for l in open(DATA / f'{f}.jsonl', encoding='utf-8')] for f in FILES}
TOKS = {'Qwen2.5': 'Qwen/Qwen2.5-0.5B-Instruct', 'Phi-3-mini': 'unsloth/Phi-3-mini-4k-instruct'}
tab = {}
for name, path in TOKS.items():
    P = Prompter(AutoTokenizer.from_pretrained(path))
    for f in FILES:
        for lv in LEVELS:
            tab[name, f, lv] = float(np.mean([P.n_tokens(r, lv) for r in rows[f]]))
pct = lambda new, old: f'{100 * (new / old - 1):+.0f}%'
L = ['# Prompt compression levels: tokens and an example', '', '> Generated by `python -m experiments.prompt_tokens`. Mean tokens, '
     'including the chat template and the answer prefix `Feasible:`.', '',
     '| Level | Removed from the level above | ' + ' | '.join(f'{n}, {f}' for n in TOKS for f in FILES) + ' |',
     '|---|---|' + '---|' * (len(TOKS) * len(FILES))]
drop = {'full': '- (full)', 'no_role_question': 'role and task sentences, "every limit must hold", the question',
        'no_field_descriptions': 'the field descriptions of D', 'compressed': 'the six rule sentences and the mass sentence (names and numbers stay)'}
for lv in LEVELS:
    L.append(f'| {lv} | {drop[lv]} | ' + ' | '.join(
        f"{tab[n, f, lv]:.0f}" + ('' if lv == 'full' else f" ({pct(tab[n, f, lv], tab[n, f, 'full'])})")
        for n in TOKS for f in FILES) + ' |')
ex = rows['test'][0]
L += ['', f"## Example (`{ex['id']}`, answer {ex['A']['feasible']}: {ex['A']['explanation']})", '']
for lv in LEVELS:
    L += [f'### {lv}', '', '```', user_text(ex, lv), '```', '']
(DATA / 'PROMPTS.md').write_text('\n'.join(L), encoding='utf-8')
print('\n'.join(L[:12]))
