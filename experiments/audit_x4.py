"""Independent audit of data/train_x4.jsonl -> data/AUDIT_X4.md. The answers are recomputed from the TEXT of K and the
numbers of D with this file's own parser and integer arithmetic (as experiments/audit.py does for the main files), and
the file is checked against every other file: same recipe, no shared D, the evaluation files untouched.

    python -m experiments.audit_x4
"""

import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'data'
x4 = [json.loads(l) for l in open(DATA / 'train_x4.jsonl', encoding='utf-8')]
train = [json.loads(l) for l in open(DATA / 'train.jsonl', encoding='utf-8')]
NUM = r'(\d+(?:\.\d+)?)'
checks = []


def check(name, ok, detail=''):
    checks.append((name, bool(ok), detail))


def answer(row):
    R = row['K']['rules']
    t = {'payload': re.fullmatch(rf'The robot can lift objects of at most {NUM} kg\.', R['payload']).group(1),
         'reach': re.fullmatch(rf'The arm can pick up an object at most {NUM} m from its base\.', R['reach_pick']).group(1),
         'height': re.fullmatch(rf'The arm can put an object on a surface at most {NUM} m high\.', R['height']).group(1),
         'clearance': re.fullmatch(rf'The robot needs at least {NUM} m of clearance at every point of its route\.',
                                   R['clearance']).group(1)}
    m = re.fullmatch(rf'Driving uses {NUM}% of the battery per meter, and at least {NUM}% must remain at the end of the '
                     r'route\.', R['battery'])
    t = {k: float(v) for k, v in t.items()}
    t['energy'], t['reserve'] = float(m.group(1)), float(m.group(2))
    masses = {p.group(1): float(p.group(2)) for p in
              (re.fullmatch(rf'the (.+) weighs {NUM} kg', x) for x in
               re.fullmatch(r'Known object masses: (.*)\.', row['K']['masses_text']).group(1).split('; '))}
    D, c = row['D'], (lambda x: round(x * 1000))
    bad = [r for r, fails in (
        ('payload', c(masses[row['G']['object']]) > c(t['payload'])), ('reach_pick', c(D['reach_pick']) > c(t['reach'])),
        ('reach_place', c(D['reach_place']) > c(t['reach'])), ('height', c(D['place_height']) > c(t['height'])),
        ('clearance', c(min(D['clearance'])) < c(t['clearance'])),
        ('battery', round(D['battery'] * 1000) < round(t['energy'] * 1000 * D['route_length']) + c(t['reserve']))) if fails]
    return not bad, bad


mism = [r['id'] for r in x4 if answer(r) != (r['A']['feasible'], r['A']['violated'])]
check('answer = rules applied to the text of K and the numbers of D (own parser, integer arithmetic)', not mism,
      f'{len(x4) - len(mism)}/{len(x4)}')
c = Counter((r['A']['feasible'], r['key_rule']) for r in x4)
check('12 (answer, key rule) buckets of equal size', len(c) == 12 and len(set(c.values())) == 1, f'{set(c.values())}')
others = {}
for f in sorted(DATA.glob('*.jsonl')):
    if f.stem not in ('train_x4', 'llmlingua2'):     # llmlingua2 holds compressed prompt text only, no D
        for line in open(f, encoding='utf-8'):
            others[json.dumps(json.loads(line)['D'], sort_keys=True)] = f.stem
keys = [json.dumps(r['D'], sort_keys=True) for r in x4]
shared = [others[k] for k in keys if k in others]
check('no D of train_x4 appears in any other file (train, val, test, the evaluation sets)', not shared, f'{Counter(shared)}' if shared else '0')
check('no D twice inside train_x4', len(set(keys)) == len(keys))
check('same vocabulary as train.jsonl (no held-out wording, object or pick-up place)',
      {r['G']['object'] for r in x4} <= {r['G']['object'] for r in train}
      and {r['G']['from'] for r in x4} <= {r['G']['from'] for r in train})
share = lambda rows, f: sum(f(r) for r in rows) / len(rows)
for name, f in (('near the limit', lambda r: r['near']), ('K-dependent', lambda r: r['k_dependent']),
                ('one violated rule among infeasible rows', lambda r: r['n_violated'] == 1)):
    a_, b_ = share(x4, f), share(train, f)
    check(f'share of rows {name} close to train.jsonl (within 3 points)', abs(a_ - b_) < 0.03, f'{100 * a_:.1f}% vs {100 * b_:.1f}%')
man = json.loads((DATA / 'manifest.json').read_text(encoding='utf-8'))
check('the main manifest still lists the 6,260 rows of the main files', man['total_rows'] == 6260)

bad = [x for x in checks if not x[1]]
L = ['# Independent audit of train_x4', '', '> Generated by `python -m experiments.audit_x4`. 9,600 extra training rows, same recipe '
     'as `train.jsonl`; the answer is recomputed from the wording of K with its own parser.', '', f'**{len(checks) - len(bad)}/{len(checks)} checks passed.**',
     '', '| Check | Result | Details |', '|---|---|---|'] + \
    [f"| {n} | {'pass' if ok else '**FAIL**'} | {d} |" for n, ok, d in checks]
(DATA / 'AUDIT_X4.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
for n, ok, d in checks:
    print('ok  ' if ok else 'FAIL', n, d)
sys.exit(1 if bad else 0)
