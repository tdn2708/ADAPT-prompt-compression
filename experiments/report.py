"""Statistics of data/ and the non-LLM reference points -> data/REPORT.md.

    python -m experiments.report [--data data]

Reference points, all trained on train.jsonl and scored once on every evaluation file (balanced accuracy; pair files
also: share of pairs with both rows right):
    majority          always the majority answer of train
    object only       the majority answer of train for the requested object (does the object give the answer away?)
    D only            gradient boosting on the measurements of D
    G + D (K-blind)   + the requested object and destination (one-hot): everything except the knowledge K
    G + K + D         + the six limits and the catalog mass of the requested object (the look-up done for it)
    slacks            gradient boosting on the six normalized slacks (the rules' own quantities; an upper reference)
"""

import argparse
import json
from collections import Counter
from pathlib import Path

import numpy as np
from sklearn.ensemble import HistGradientBoostingClassifier

from adapt.problem import ALL_OBJECTS, ALL_PLACES, LIMITS, RULES

ap = argparse.ArgumentParser()
ap.add_argument('--data', default=str(Path(__file__).resolve().parent.parent / 'data'))
a = ap.parse_args()
DATA = Path(a.data)
FILES = ['train', 'val', 'test', 'near_threshold', 'd_pairs', 'k_pairs', 'g_pairs', 'unseen', 'longer_than_train']
EVAL = ['test', 'near_threshold', 'd_pairs', 'k_pairs', 'g_pairs', 'unseen', 'longer_than_train']
rows = {f: [json.loads(l) for l in open(DATA / f'{f}.jsonl', encoding='utf-8')] for f in FILES}
pct = lambda x: f'{100 * x:.1f}'
OBJ, PLC = sorted(ALL_OBJECTS), sorted(ALL_PLACES)


def d_feats(r):
    D = r['D']
    return [D['reach_pick'], D['reach_place'], D['place_height'], min(D['clearance']), float(np.mean(D['clearance'])),
            len(D['clearance']), D['route_length'], D['battery']]


def g_feats(r):
    return [float(r['G']['object'] == o) for o in OBJ] + [float(r['G']['to'] == p) for p in PLC]


def k_feats(r):
    return [r['K']['limits'][k] for k in LIMITS] + [r['K']['masses'][r['G']['object']], len(r['K']['masses'])]


FEATS = {'D only': d_feats, 'G + D (K-blind)': lambda r: g_feats(r) + d_feats(r),
         'G + K + D': lambda r: g_feats(r) + k_feats(r) + d_feats(r), 'slacks': lambda r: [r['slack'][k] for k in RULES]}
y_of = lambda rs: np.array([r['A']['feasible'] for r in rs])


def balanced(y, p):
    return float(np.mean([np.mean(p[y == k] == k) for k in (True, False) if np.any(y == k)]))


def pairs_right(rs, p):
    ok = {}
    for r, pp in zip(rs, p):
        ok.setdefault(r['pair_id'], []).append(pp == r['A']['feasible'])
    return float(np.mean([all(v) for v in ok.values()]))


preds = {}
ytr = y_of(rows['train'])
maj = Counter(ytr.tolist()).most_common(1)[0][0]
preds['majority'] = {f: np.full(len(rows[f]), maj) for f in EVAL}
by_obj = {}
for r in rows['train']:
    by_obj.setdefault(r['G']['object'], []).append(r['A']['feasible'])
obj_major = {o: Counter(v).most_common(1)[0][0] for o, v in by_obj.items()}
preds['object only'] = {f: np.array([obj_major.get(r['G']['object'], maj) for r in rows[f]]) for f in EVAL}
for name, fn in FEATS.items():
    clf = HistGradientBoostingClassifier(random_state=0).fit(np.array([fn(r) for r in rows['train']]), ytr)
    preds[name] = {f: clf.predict(np.array([fn(r) for r in rows[f]])) for f in EVAL}

# ---- statistics ---------------------------------------------------------------------------------------------------------
man = json.loads((DATA / 'manifest.json').read_text(encoding='utf-8'))
L = ['# Dataset report (G, K, D, A): pick-and-place robot', '',
     '> Generated by `python -m experiments.report`. Independent audit: `data/AUDIT.md`.', '',
     '## 1. Size', '', '| File | Rows | Feasible | Near threshold (flip margin < 10%) | K-dependent | Rejected while generating |',
     '|---|---|---|---|---|---|']
for f in FILES:
    rs = rows[f]
    L.append(f"| `{f}.jsonl` | {len(rs)} | {pct(np.mean(y_of(rs)))}% | {pct(np.mean([r['near'] for r in rs]))}% | "
             f"{pct(np.mean([r['k_dependent'] for r in rs]))}% | {sum(man['rejected'][f].values())} |")
L += [f"| Total | {sum(len(v) for v in rows.values())} | | | | |", '',
      '"K-dependent": moving one limit of K, or the mass of the requested object, within its sampling range changes the '
      'answer. "Rejected while generating": draws thrown away (outside the wanted band, or a repeated D); the validity '
      'check rejects 0 rows because the generator is correct by construction.', '']
tr = rows['train']
L += ['## 2. Training set', '', '| Rule | Violated (among infeasible rows) | Key rule of the row |', '|---|---|---|']
nf = [r for r in tr if not r['A']['feasible']]
for k in RULES:
    L.append(f"| {k} | {pct(np.mean([k in r['A']['violated'] for r in nf]))}% | {sum(r['key_rule'] == k for r in tr)} |")
nv = Counter(r['n_violated'] for r in nf)
L += ['', f"Rules violated in an infeasible row: " +
      ', '.join(f'{k} rule(s): {pct(v / len(nf))}%' for k, v in sorted(nv.items())) + '.',
      f"Size of the mass catalog: " + ', '.join(f'{k}: {v}' for k, v in sorted(Counter(r['catalog_size'] for r in tr).items())) +
      f". Number of clearance readings: " + ', '.join(f'{k}: {v}' for k, v in sorted(Counter(r['n_readings'] for r in tr).items())) + '.',
      '']
fm = np.array([r['flip_margin'] for r in tr if r['flip_margin'] is not None])
L += [f"Flip margin (smallest relative change of ONE quantity that changes the answer): median {pct(np.median(fm))}%, "
      f"25th percentile {pct(np.quantile(fm, .25))}%, 75th {pct(np.quantile(fm, .75))}%; "
      f"{pct(np.mean([r['flip_margin'] is None for r in tr]))}% of the rows cannot be flipped by one quantity (2 or more rules violated).", '']

# ---- reference points -------------------------------------------------------------------------------------------------
L += ['## 3. Reference points without a language model', '',
      'Trained on `train.jsonl`, scored once. Balanced accuracy (%); pair files: also the share of pairs with both rows right.', '',
      '| Reference | ' + ' | '.join(EVAL) + ' |', '|---|' + '---|' * len(EVAL)]
for name, P in preds.items():
    cells = []
    for f in EVAL:
        b = pct(balanced(y_of(rows[f]), P[f]))
        cells.append(f"{b} / {pct(pairs_right(rows[f], P[f]))}" if f in ('d_pairs', 'k_pairs', 'g_pairs') else b)
    L.append(f'| {name} | ' + ' | '.join(cells) + ' |')
L += ['', 'Reading: "G + D (K-blind)" sees everything except K. In `k_pairs` the two rows of a pair share G and D, so this reference always '
      'gives both rows the same answer and its pair rate is 0 by construction; in `g_pairs` the two rows differ only in the requested object. '
      '"slacks" receives the six rule quantities ready-made, so it is an upper reference.']
(DATA / 'REPORT.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
print('\n'.join(L))
